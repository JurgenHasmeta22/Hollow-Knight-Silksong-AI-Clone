"""Embeds the longer generated sound-effect recordings in tools/audio/*.mp3 into assets/audio/sfx_bank.js.

Usage: python tools/build_sfx_bank.py

Each file is a single recording that holds several takes of one sound (a few seconds of blade swishes, growls, voices...).
They are embedded as base64 so the game still runs from file:// (the same reason sfx_pack.js is embedded). The game
cuts each recording into its separate takes when it starts (see Audio.findSegments in src/audio/audio.js), and a name
that ends in a digit (voice1, voice2) joins one bank called `voice`, so Audio.play('voice') picks any take of either.
"""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / 'tools' / 'audio'
OUT = ROOT / 'assets' / 'audio' / 'sfx_bank.js'


def main():
    bank = {}

    for f in sorted(SRC.glob('*.mp3')):
        bank[f.stem] = 'data:audio/mpeg;base64,' + base64.b64encode(f.read_bytes()).decode('ascii')

    text = '// Generated by tools/build_sfx_bank.py from tools/audio/*.mp3: do not edit by hand.\n'
    text += 'window.BW_SFX_BANK = ' + json.dumps(bank, indent=0) + ';\n'
    OUT.write_text(text, encoding='utf-8')
    print(len(bank), 'recordings,', OUT.stat().st_size, 'bytes ->', OUT)


if __name__ == '__main__':
    main()
